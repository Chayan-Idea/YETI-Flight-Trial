const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const index=read('index.html');
const editor=read('js/flight-trial-sop-editor.js');
const serviceWorker=read('service-worker.js');
const sop=JSON.parse(read('data/flight-trial-sop.json'));
assert.equal(sop.schemaVersion,1,'SOP schema version must be supported');
assert.ok(Number.isInteger(sop.revision) && sop.revision >= 1,'Central SOP revision must be a positive integer and may increase as Admins publish updates');
assert.match(sop.html,/<article class="flight-trial-reading-document">/,'Central SOP must preserve the existing document wrapper');
assert.match(sop.html,/<h3>10\. DOCUMENT CONTROL &amp; RELEASE<\/h3>/,'Initial SOP must retain its final document-control section');
assert.match(index,/flightTrialSopAdminTools/,'Admin SOP controls must be present');
assert.match(index,/flight-trial-sop-editor\.js\?v=1/,'SOP editor script must be loaded');
assert.match(editor,/document\.body\.dataset\.yetiAuthRole==='admin'/,'Editing and publishing must require the Admin role');
assert.match(editor,/Authorization':'Bearer '\+token/,'GitHub writes must use the token supplied at save time');
assert.match(editor,/tokenInput\.value=''/,'Token input must be cleared after reading it');
assert.doesNotMatch(editor,/localStorage|sessionStorage\.setItem|document\.cookie/,'Editor must not persist the GitHub token');
assert.match(editor,/sha:meta\.sha/,'GitHub content updates must use the latest file SHA to detect conflicts');
assert.match(editor,/revision:currentRevision\+1/,'Each save must increment the SOP revision');
assert.match(serviceWorker,/yeti-flight-trial-shell-v202/,'Service worker cache must be versioned for the editor release');
assert.match(serviceWorker,/flight-trial-sop-editor\.js/,'Editor script must be precached');
assert.match(serviceWorker,/flight-trial-sop\.json/,'SOP data must be precached for offline fallback');
console.log('Flight Trial SOP central storage and Admin editor checks passed.');
